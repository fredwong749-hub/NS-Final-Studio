# ---------------------------------------------------------------- LUT（自产）
LOOKS = {   # 整集统一的两条 look；参数小幅，只做“定调”，不改曝光（K-EDT-801）
    "night": {"s_curve": 0.12, "lift": 0.012, "sat": 0.96,
              "shadow": (-0.010, 0.004, 0.018), "high": (0.016, 0.006, -0.010)},
    "day": {"s_curve": 0.14, "lift": 0.006, "sat": 1.03,
            "shadow": (0.0, 0.0, 0.004), "high": (0.010, 0.004, -0.006)},
}


def lut_path(kind: str) -> Path:
    return LUT_DIR / f"{kind}_v1.cube"


def make_lut(kind: str, n: int = 33) -> Path:
    lk = LOOKS[kind]
    g = np.linspace(0, 1, n)
    b, gg, r = np.meshgrid(g, g, g, indexing="ij")          # .cube：R 变化最快
    rgb = np.stack([r, gg, b], -1)
    sm = rgb * rgb * (3 - 2 * rgb)
    y = (1 - lk["s_curve"]) * rgb + lk["s_curve"] * sm
    y = lk["lift"] + (1 - lk["lift"]) * y
    lum = (0.2126 * y[..., 0] + 0.7152 * y[..., 1] + 0.0722 * y[..., 2])[..., None]
    y = lum + (y - lum) * lk["sat"]
    y = y + (1 - lum) ** 2 * np.array(lk["shadow"]) + lum ** 2 * np.array(lk["high"])
    y = np.clip(y, 0, 1)
    LUT_DIR.mkdir(parents=True, exist_ok=True)
    p = lut_path(kind)
    lines = [f"# NS-Final Studio DIRECTOR look '{kind}' v1 (generated by tools/director/post_pass.py; self-authored, no third-party license)",
             f"# params {json.dumps(lk)}", f'TITLE "nsfs_{kind}_v1"', f"LUT_3D_SIZE {n}", "DOMAIN_MIN 0 0 0", "DOMAIN_MAX 1 1 1"]
    lines += [f"{v[0]:.6f} {v[1]:.6f} {v[2]:.6f}" for v in y.reshape(-1, 3)]
    p.write_text("\n".join(lines) + "\n", encoding="ascii")
    return p


# ---------------------------------------------------------------- 素材库 / 许可证
def register_licenses() -> dict:
    """data/sfx_lib/kenney_* 每个文件登记许可证 + sha256（只登记，不改文件）"""
    reg = {"_doc": "DIRECTOR 后期层音效素材许可证登记（K-EDT-802）。只收免费可商用素材；合成声床不在此表（自产）。",
           "packs": {}, "files": {}}
    for d in sorted(SFX_LIB.glob("kenney_*")):
        lic = (d / "License.txt").read_text(encoding="utf-8", errors="replace") if (d / "License.txt").exists() else ""
        ok = "CC0" in lic
        reg["packs"][d.name] = {"license": "CC0 1.0（Creative Commons Zero）" if ok else "未知",
                                "url": "https://creativecommons.org/publicdomain/zero/1.0/",
                                "source": f"https://kenney.nl/assets/{d.name.removeprefix('kenney_')}",
                                "commercial_ok": ok, "license_file": str((d / "License.txt").relative_to(ROOT)).replace("\\", "/"),
                                "downloaded": "2026-11-02（DIRECTOR，免费下载，未付费）"}
        for f in sorted(d.rglob("*.ogg")):
            reg["files"][str(f.relative_to(ROOT)).replace("\\", "/")] = {
                "pack": d.name, "sha256": hashlib.sha256(f.read_bytes()).hexdigest()[:16]}
    LICENSES.write_text(json.dumps(reg, ensure_ascii=False, indent=1), encoding="utf-8")
    return reg


def lib_files(stem: str) -> list[Path]:
    return sorted(p for p in SFX_LIB.glob("kenney_*/**/*.ogg") if re.fullmatch(re.escape(stem) + r"_?\d*", p.stem))


# 关键词 → 素材（顺序 = 优先级）；gain = 相对 −12 dBFS 峰值归一后的增益
EVENTS = [
    (r"皮鞋|踏地|鞋跟|高跟|脚步", "footstep_concrete", -10.0, "steps"),
    (r"开门|推门|门开", "doorOpen", -8.0, "one"),
    (r"关门|门关|带上门", "doorClose", -8.0, "one"),
    (r"键盘|敲击", "click", -20.0, "taps"),
    (r"衣料|布料|外套|衣服", "cloth", -16.0, "one"),
    (r"椅", "creak", -18.0, "one"),
    (r"纸|文件|翻页|书", "bookFlip", -16.0, "one"),
    (r"叮", "bong", -20.0, "one"),
    (r"杯|玻璃", "impactGlass_light", -16.0, "one"),
]
BEDS = [(r"空调|低鸣|办公|写字楼|室内", "hvac"), (r"雨", "rain"), (r"车流|街|城市|马路", "traffic")]


def synth_bed(kind: str, n: int, seed: int) -> np.ndarray:
    """程序合成环境声床（自产），RMS 归一到 1"""
    from ns_post import assemble as A
    base = A.room_tone(n, SR, seed=seed)
    f = np.fft.rfftfreq(n, 1 / SR)
    spec = np.fft.rfft(base, axis=0)
    if kind == "hvac":        # 空调：低频为主 + 很轻的 100/120 Hz 嗡声
        spec *= (1 / (1 + (f / 350.0) ** 2))[:, None]
        y = np.fft.irfft(spec, n=n, axis=0)
        t = np.arange(n) / SR
        y += 0.08 * np.std(y) * (np.sin(2 * np.pi * 100 * t) + 0.5 * np.sin(2 * np.pi * 120 * t))[:, None]
    elif kind == "rain":
        spec *= ((f > 1500) * (1 / (1 + (f / 9000.0) ** 2)))[:, None]
        y = np.fft.irfft(spec, n=n, axis=0)
    else:                     # traffic：低频隆隆 + 慢起伏
        spec *= (1 / (1 + (f / 180.0) ** 2))[:, None]
        y = np.fft.irfft(spec, n=n, axis=0)
        y *= (0.7 + 0.3 * np.sin(2 * np.pi * np.arange(n) / SR / 7.0))[:, None]
    y = y.astype(np.float32)
    return y / max(float(np.sqrt((y ** 2).mean())), 1e-9)


def load_clip(ff, path: Path, work: Path) -> np.ndarray:
    from ns_post import assemble as A
    x = A.read_audio(ff, path, SR, channels=2, work=work)
    pk = float(np.abs(x).max()) or 1.0
    return x * np.float32(10 ** (-12 / 20) / pk)


def plan_sfx(script_shots: dict, tl: dict, scene_of) -> tuple[list, list, list]:
    """→ (events, beds, unmatched)。events: {shot, t, file, gain_db, kw}；beds: {scene, kind, start_s, end_s}"""
    rng = np.random.default_rng(20261102)
    events, unmatched, beds = [], [], []
    bed_by_scene = {}
    for s in tl["shots"]:
        rec = script_shots.get(int(s["index"])) or {}
        snd = str(rec.get("sound") or "").split("【")[0]
        a, d = float(s["start_s"]), float(s["duration_s"])
        sc = rec.get("scene_id") or scene_of(s["shot"]) or "?"
        kind = next((k for rx, k in BEDS if re.search(rx, snd)), None)
        if kind and sc not in bed_by_scene:
            bed_by_scene[sc] = kind
        for clause in re.split(r"[，,；;。]", snd):
            clause = clause.strip()
            if not clause or re.search(r"呼吸|配乐|^\s*$", clause):
                continue
            hit = next(((rx, st, g, mode) for rx, st, g, mode in EVENTS if re.search(rx, clause)), None)
            if not hit:
                if not any(re.search(rx, clause) for rx, _ in BEDS):
                    unmatched.append({"shot": s["shot"], "text": clause})
                continue
            rx, stem, g, mode = hit
            files = lib_files(stem)
            if not files:
                unmatched.append({"shot": s["shot"], "text": clause, "why": f"素材库没有 {stem}"})
                continue
            if mode == "steps":
                approach, recede, stop = bool(re.search(r"由远及近|走近|靠近", clause)), bool(re.search(r"渐远|走远|离开", clause)), bool(re.search(r"停", clause))
                if re.search(r"一声|一下", clause):
                    ts, gs = [0.35], [0.0]
                else:
                    span = d * (0.7 if stop else 0.95)
                    k = max(2, int(span / 0.55))
                    ts = [0.1 * d + i * (span - 0.1 * d) / k for i in range(k)]
                    gs = [(-12 + 12 * i / max(1, k - 1)) if approach else (-12 * i / max(1, k - 1) if recede else 0.0) for i in range(k)]
                    ts = [t / d for t in ts]
                for t, gg in zip(ts, gs):
                    events.append({"shot": s["shot"], "t": round(a + t * d, 3), "file": files[int(rng.integers(len(files)))],
                                   "gain_db": g + gg, "kw": clause})
            elif mode == "taps":
                n = 2 if re.search(r"两下|轻响|一下", clause) else 4
                t0 = a + 0.15 * d
                for i in range(n):
                    events.append({"shot": s["shot"], "t": round(t0 + i * 0.16 + float(rng.uniform(0, 0.04)), 3),
                                   "file": files[int(rng.integers(len(files)))], "gain_db": g, "kw": clause})
            else:
                events.append({"shot": s["shot"], "t": round(a + 0.4 * d, 3), "file": files[int(rng.integers(len(files)))],
                               "gain_db": g, "kw": clause})
    # 每个场景至少一条声床（剧本没写时按室内底噪 hvac；K-EDT-802）
    scenes = []
    for s in tl["shots"]:
        rec = script_shots.get(int(s["index"])) or {}
        sc = rec.get("scene_id") or scene_of(s["shot"]) or "?"
        if not scenes or scenes[-1][0] != sc:
            scenes.append([sc, float(s["start_s"]), float(s["start_s"]) + float(s["duration_s"])])
        else:
            scenes[-1][2] = float(s["start_s"]) + float(s["duration_s"])
    for sc, a, b in scenes:
        beds.append({"scene": sc, "kind": bed_by_scene.get(sc, "hvac"), "start_s": a, "end_s": b,
                     "source": "剧本【声音】" if sc in bed_by_scene else "默认室内底噪"})
    return events, beds, unmatched


# ---------------------------------------------------------------- 调色
def shot_means(video: Path, shots: list[dict]) -> dict:
    """每镜 → {frame: 整帧 RGB 均值, face: 主脸中心区域 RGB 均值或 None}（3 帧平均；YuNet 同 review.py）"""
    import cv2
    sys.path.insert(0, str(ROOT / "tools/ep02_director"))
    import review as RV
    faces = RV.Faces()
    cap = cv2.VideoCapture(str(video))
    fps = cap.get(cv2.CAP_PROP_FPS) or 24.0
    out = {}
    for s in shots:
        a = s["start_s"]
        fr_acc, face_acc = [], []
        for f in (0.2, 0.5, 0.8):
            cap.set(cv2.CAP_PROP_POS_FRAMES, int((a + f * s["duration_s"]) * fps))
            ok, fr = cap.read()
            if not ok:
                continue
            sm = cv2.resize(fr, (360, 640))
            fr_acc.append(sm.reshape(-1, 3).mean(0)[::-1])
            rgb = cv2.cvtColor(sm, cv2.COLOR_BGR2RGB)
            fs = faces.detect(rgb) if faces.ok else []
            for fc in (fs if fs is not None else []):
                x, y, w, h = [int(v) for v in fc[:4]]
                roi = sm[max(0, y + h // 4): y + 3 * h // 4, max(0, x + w // 4): x + 3 * w // 4]
                if not roi.size or h < 24:
                    continue
                who = None
                if faces.refs:     # 按人对齐：同一个角色的肤色跨镜一致（不同角色肤色本来就不同）
                    e = faces.embed(rgb, fc)
                    cs = {k: float(RV.QF.cosine(e, r)) for k, r in faces.refs.items()}
                    k = max(cs, key=cs.get)
                    who = k if cs[k] >= 0.25 else None
                if who:
                    face_acc.append((who, roi.reshape(-1, 3).mean(0)[::-1]))
        if fr_acc:
            per = {}
            for who, v in face_acc:
                per.setdefault(who, []).append(v)
            out[s["shot"]] = {"frame": np.mean(fr_acc, 0), "faces": {k: np.mean(v, 0) for k, v in per.items()},
                              "n_faces": {k: len(v) for k, v in per.items()}}
    cap.release()
    return out


def grade_plan(video: Path, tl: dict, scene_of, tod_of) -> dict:
    """同场对齐：有脸的镜按脸部肤色对齐到本场脸部中位（观众看的是人，K-EDT-801 A/B 结论：按整帧对齐会把脸部 ΔE 拉大
    6.7 → 8.9）；没脸的镜按整帧对齐、强度减半。每通道增益限制在 ±8%"""
    means = shot_means(video, tl["shots"])
    face_by, frame_by = {}, {}
    for s in tl["shots"]:
        m = means.get(s["shot"])
        if m and not s.get("placeholder"):     # 占位静帧不当参照
            sc = scene_of(s["shot"]) or "?"
            frame_by.setdefault(sc, []).append(m["frame"])
            for who, v in m["faces"].items():
                face_by.setdefault((sc, who), []).append(v)
    plan = {}
    for s in tl["shots"]:
        sc = scene_of(s["shot"]) or "?"
        m = means.get(s["shot"])
        basis, gain = "none", np.ones(3)
        who = max(m["n_faces"], key=m["n_faces"].get) if m and m["n_faces"] else None
        if who and len(face_by.get((sc, who), [])) >= 2:
            gain, basis = np.median(face_by[(sc, who)], 0) / np.maximum(m["faces"][who], 1.0), f"face:{who}"
        elif m is not None and frame_by.get(sc):
            gain, basis = 1 + 0.5 * (np.median(frame_by[sc], 0) / np.maximum(m["frame"], 1.0) - 1), "frame_half"
        if MATCH == "none":
            gain, basis = np.ones(3), "none"
        gain = np.clip(gain, 0.92, 1.08)
        plan[s["shot"]] = {"scene": sc, "look": tod_of(s["shot"]), "basis": basis, "gain_rgb": [round(float(x), 4) for x in gain],
                           "face_rgb": [round(float(x), 1) for x in m["faces"][who]] if who else None}
    return plan


def render_graded(ff_bin: str, video: Path, tl: dict, plan: dict, out_v: Path) -> None:
    fps = 24
    parts, labels = [], []
    for i, s in enumerate(tl["shots"]):
        a = round(float(s["start_s"]) * fps)
        b = round((float(s["start_s"]) + float(s["duration_s"])) * fps)
        p = plan[s["shot"]]
        lut = lut_path(p["look"]).relative_to(ROOT).as_posix()
        r, g, bb = p["gain_rgb"]
        parts.append(f"[0:v]trim=start_frame={a}:end_frame={b},setpts=PTS-STARTPTS,"
                     f"colorchannelmixer=rr={r}:gg={g}:bb={bb},lut3d=file={lut}:interp=tetrahedral[v{i}]")
        labels.append(f"[v{i}]")
    fc = ";".join(parts) + ";" + "".join(labels) + f"concat=n={len(labels)}:v=1:a=0,format=yuv420p[vout]"
    cmd = [ff_bin, "-y", "-hide_banner", "-loglevel", "error", "-threads", THREADS, "-i", str(video),
           "-filter_complex", fc, "-map", "[vout]", "-c:v", "libx264", "-crf", "18", "-preset", "medium",
           "-threads", THREADS, "-colorspace", "bt709", "-color_primaries", "bt709", "-color_trc", "bt709",
           "-color_range", "tv", "-an", str(out_v)]
    subprocess.run(cmd, check=True, cwd=str(ROOT))


# ---------------------------------------------------------------- 主流程
def script_shots_for(script: Path, ep: int, n_shots: int) -> tuple[dict, str | None]:
    d = json.loads(script.read_text(encoding="utf-8"))
    e = next((x for x in d.get("episodes") or [] if int(x.get("number")) == ep), None)
    shots = {int(s["index"]): s for s in (e or {}).get("shots") or []}
    warn = None if len(shots) == n_shots else f"剧本 {script.name} ep{ep:02d} 有 {len(shots)} 镜，成片 {n_shots} 镜——剧本已改版？用 --script 指定当时的版本"
    return shots, warn


def run(video: Path, tlp: Path, script: Path, out: Path, do_grade=True, do_sfx=True) -> dict:
    from ns_post import assemble as A
    from ns_post.ffmpeg import FFmpeg, find_tools
    tl = json.loads(tlp.read_text(encoding="utf-8"))
    ep = int(tl["episode"])
    sshots, warn = script_shots_for(script, ep, len(tl["shots"]))
    if warn:
        raise SystemExit(warn)
    by_idx = {f"ep{ep:02d}-S{k}": v for k, v in sshots.items()}
    scene_of = lambda sid: (by_idx.get(sid) or {}).get("scene_id")   # noqa: E731
    tod_of = lambda sid: "night" if re.search(r"night|夜|傍晚|dusk", f"{scene_of(sid) or ''} {(by_idx.get(sid) or {}).get('img_prompt') or ''}", re.I) else "day"   # noqa: E731
    ff = FFmpeg.discover()
    ff_bin = find_tools()[0]
    t0 = time.time()
    work = Path(tempfile.mkdtemp(prefix="nsfs_post_"))
    info = {"by": "DIRECTOR post_pass", "at": time.strftime("%Y-%m-%d %H:%M:%S"), "input": A._rel(video),
            "script": A._rel(script), "steps": []}
    # 1. 调色
    vid = video
    if do_grade:
        for k in LOOKS:
            make_lut(k)
        plan = grade_plan(video, tl, scene_of, tod_of)
        gv = work / "graded.mp4"
        render_graded(ff_bin, video, tl, plan, gv)
        vid = gv
        info["grade"] = {"luts": {k: A._rel(lut_path(k)) for k in LOOKS}, "per_shot": plan, "rule": "K-EDT-801"}
        info["steps"].append("grade")
    # 2. 音效 + 3. 响度
    mix = A.read_audio(ff, video, SR, channels=2, work=work)
    n = len(mix)
    sfx_block = None
    if do_sfx:
        lic = register_licenses()
        events, beds, unmatched = plan_sfx(sshots, tl, scene_of)
        speech = [(float(x["start_s"]), float(x["end_s"])) for x in tl.get("speech") or []]
        ev_track = np.zeros_like(mix)
        cache = {}
        for e in events:
            if e["file"] not in cache:
                cache[e["file"]] = load_clip(ff, e["file"], work)
            c = cache[e["file"]] * np.float32(10 ** (e["gain_db"] / 20))
            k0 = int(e["t"] * SR)
            k1 = min(n, k0 + len(c))
            if k0 < n:
                ev_track[k0:k1] += c[: k1 - k0]
        bed_track = np.zeros_like(mix)
        for i, b in enumerate(beds):
            k0, k1 = int(b["start_s"] * SR), min(n, int(b["end_s"] * SR))
            y = synth_bed(b["kind"], k1 - k0, 20261102 + i) * np.float32(10 ** (-44 / 20))   # 声床 RMS −44 dBFS（归一前）
            y = A._fade_edges(y, SR, 0.3)
            bed_track[k0:k1] += y
        ev_track *= A.gain_envelope(n, SR, [(a, b, 8.0) for a, b in speech], 0.08)[:, None]
        bed_track *= A.gain_envelope(n, SR, [(a, b, 6.0) for a, b in speech], 0.15)[:, None]
        mix = mix + ev_track + bed_track
        files_used = sorted({A._rel(e["file"]) for e in events})
        lic_ok = all(f in lic["files"] and lic["packs"][lic["files"][f]["pack"]]["commercial_ok"] for f in files_used)
        sfx_block = {"rule": "K-EDT-802", "events": [{**e, "file": A._rel(e["file"])} for e in events], "beds": beds,
                     "unmatched": unmatched, "files": files_used, "licenses_ok": lic_ok,
                     "license_note": "动作音效 Kenney CC0 1.0（data/sfx_lib/LICENSES.json，含 sha256）；声床程序合成（自产）",
                     "duck": {"events_db": 8.0, "beds_db": 6.0}}
        info["steps"].append("sfx")
    raw = work / "mix.f32"
    mix.astype(np.float32).tofile(raw)
    wav = work / "mix.wav"
    loud = A.loudnorm(ff, raw, wav, A.Settings())
    info["steps"].append("loudnorm")
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([ff_bin, "-y", "-hide_banner", "-loglevel", "error", "-i", str(vid), "-i", str(wav), "-map", "0:v:0", "-map", "1:a:0",
                    "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-shortest", "-movflags", "+faststart", str(out)], check=True)
    meas = A.measure_loudness(ff, out)
    info["loudness"] = {"target_lufs": -14.0, "measured": meas, "loudnorm": loud, "rule": "K-EDT-803"}
    info["seconds"] = round(time.time() - t0, 1)
    tl2 = dict(tl)
    tl2["output"] = A._rel(out)
    tl2["post"] = info
    tl2["loudness"] = info["loudness"]
    if sfx_block:
        tl2["sfx"] = sfx_block
    if do_grade:
        tl2["grade"] = info["grade"]
    tl2.setdefault("warnings", [])
    out.with_suffix(".timeline.json").write_text(json.dumps(tl2, ensure_ascii=False, indent=1, default=str), encoding="utf-8")
    print(f"[post_pass] {A._rel(out)} steps={info['steps']} loud={meas} sfx_events={len((sfx_block or {}).get('events', []))} "
          f"unmatched={len((sfx_block or {}).get('unmatched', []))} {info['seconds']}s")
    return tl2


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("video")
    ap.add_argument("--timeline")
    ap.add_argument("--script", default=str(ROOT / "data/import/script_v2.json"))
    ap.add_argument("--out")
    ap.add_argument("--no-grade", action="store_true")
    ap.add_argument("--no-sfx", action="store_true")
    ap.add_argument("--match", choices=("face", "none"), default="face")
    a = ap.parse_args(argv)
    global MATCH
    MATCH = a.match
    v = Path(a.video)
    v = v if v.is_absolute() else ROOT / v
    tlp = Path(a.timeline) if a.timeline else v.with_suffix(".timeline.json")
    tlp = tlp if tlp.is_absolute() else ROOT / tlp
    out = Path(a.out) if a.out else v.with_name(v.stem + "_post.mp4")
    out = out if out.is_absolute() else ROOT / out
    sc = Path(a.script)
    run(v, tlp, sc if sc.is_absolute() else ROOT / sc, out, not a.no_grade, not a.no_sfx)


if __name__ == "__main__":
    main()
